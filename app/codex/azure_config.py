"""Write a project-local Codex config that uses Vitality's Azure OpenAI settings."""

from __future__ import annotations

from pathlib import Path

import config


def azure_codex_ready() -> bool:
    """Whether Azure chat credentials are complete enough for Codex."""
    return bool(
        config.is_azure_chat_configured()
        and config.AZURE_OPENAI_ENDPOINT
        and config.AZURE_OPENAI_API_KEY
        and config.AZURE_OPENAI_API_VERSION
    )


def resolve_codex_model() -> str | None:
    """Return the Azure deployment name Codex should call."""
    if config.CODEX_MODEL:
        # Accept either a logical key or a raw deployment name.
        try:
            return config.resolve_chat_deployment(config.CODEX_MODEL)
        except ValueError:
            return config.CODEX_MODEL
    if not azure_codex_ready():
        return None
    return config.resolve_chat_deployment(None)


def azure_base_url() -> str:
    endpoint = config.AZURE_OPENAI_ENDPOINT.rstrip("/")
    if endpoint.endswith("/openai"):
        return endpoint
    return f"{endpoint}/openai"


def write_project_codex_config(home: str | Path | None = None) -> Path | None:
    """Materialize ``config.toml`` under the project Codex home.

    The API key stays in the process environment via ``env_key``; it is never
    written to disk. Returns None when Azure chat is not configured.
    """
    if not azure_codex_ready():
        return None
    root = Path(home or config.CODEX_HOME)
    root.mkdir(parents=True, exist_ok=True)
    model = resolve_codex_model() or config.resolve_chat_deployment(None)
    api_version = config.AZURE_OPENAI_API_VERSION
    contents = f"""# Generated by VitaLITy from Azure OpenAI settings.
# Do not commit this directory. The API key is read from AZURE_OPENAI_API_KEY.

model = "{model}"
model_provider = "azure"

[model_providers.azure]
name = "Azure"
base_url = "{azure_base_url()}"
env_key = "AZURE_OPENAI_API_KEY"
wire_api = "responses"
query_params = {{ api-version = "{api_version}" }}
"""
    path = root / "config.toml"
    path.write_text(contents, encoding="utf-8")
    return path


def subprocess_env(base: dict[str, str] | None = None) -> dict[str, str]:
    """Environment for the Codex app-server child process."""
    env = dict(base or {})
    env["CODEX_HOME"] = config.CODEX_HOME
    if config.AZURE_OPENAI_API_KEY:
        env["AZURE_OPENAI_API_KEY"] = config.AZURE_OPENAI_API_KEY
        # Some Codex builds also look at OPENAI_API_KEY when using apikey auth.
        env.setdefault("OPENAI_API_KEY", config.AZURE_OPENAI_API_KEY)
    if config.AZURE_OPENAI_ENDPOINT:
        env["AZURE_OPENAI_ENDPOINT"] = config.AZURE_OPENAI_ENDPOINT
    if config.AZURE_OPENAI_API_VERSION:
        env["AZURE_OPENAI_API_VERSION"] = config.AZURE_OPENAI_API_VERSION
    return env
